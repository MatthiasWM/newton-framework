#!/bin/sh
# Assemble newtdump's native functions (Matt/NewtDump/Newton/PhysNatives.s)
# into Matt/NewtDump/Newton/PhysNatives.ns: the code as a binary of class
# 'code (hex) and, per native, its offset in it and its number of
# arguments. The .ns file is checked in: building newtdump needs no ARM
# tools, only changing the natives does (GNU binutils for ARM:
# brew install arm-none-eabi-binutils, or apt install binutils-arm-none-eabi).
#
#   Matt/tools/build_newtdump_natives.sh
set -e
REPO=$(cd "$(dirname "$0")/../.." && pwd)
SRC="$REPO/Matt/NewtDump/Newton/PhysNatives.s"
OUT="$REPO/Matt/NewtDump/Newton/PhysNatives.ns"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# ARMv4 (the StrongARM: no Thumb, no bx; the assembler refuses them),
# big-endian
arm-none-eabi-as -EB -march=armv4 -o "$TMP/natives.o" "$SRC"
arm-none-eabi-objcopy -O binary "$TMP/natives.o" "$TMP/natives.bin"
arm-none-eabi-nm "$TMP/natives.o" > "$TMP/natives.sym"

python3 - "$SRC" "$TMP/natives.bin" "$TMP/natives.sym" "$OUT" <<'EOF'
import re, sys
src, binary, symbols, out = sys.argv[1:5]
code = open(binary, "rb").read()
addresses = {}
for line in open(symbols):
    parts = line.split()
    if len(parts) == 3:
        addresses[parts[2]] = int(parts[0], 16)
natives = re.findall(r"^@ native (\w+) (\d+)$", open(src).read(), re.M)
hexcode = code.hex().upper()
lines = ['"%s"' % hexcode[i:i + 64] for i in range(0, len(hexcode), 64)]
with open(out, "w") as f:
    f.write("// PhysNatives.ns: generated by Matt/tools/build_newtdump_natives.sh from\n")
    f.write("// PhysNatives.s; don't edit, assemble again.\n")
    f.write("//\n")
    f.write("// kPhysNativeCode: the ARM code (%d bytes); a constant per native: a\n" % len(code))
    f.write("// frame {class: 'BinCFunction, code, numArgs, offset}, so `call kPhysMap\n")
    f.write("// with (...)` in Extension.ns puts it into the extension's literals.\n\n")
    f.write("DefineGlobalConstant('kPhysNativeCode, MakeBinaryFromHex(\n  ")
    f.write("\n  ".join(lines))
    f.write(", 'code));\n\n")
    for name, n in natives:
        f.write("DefineGlobalConstant('k%s, {class: 'BinCFunction, code: kPhysNativeCode, numArgs: %s, offset: %d});\n"
                % (name, n, addresses[name]))
print("%s: %d bytes, %d natives" % (out, len(code), len(natives)))
EOF
