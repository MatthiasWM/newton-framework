/*------------------------------------------------------------------------------
	Put a run of pixels into the line: black ones are 1s. Return whether the
	line has room left; outBytes, the bytes completed.
------------------------------------------------------------------------------*/

Boolean
TT4FaxLine::EmitBits(RunColor inColor, int inRun, int * outBytes)
{
	if (fLine >= fLineEnd)
	{
		*outBytes = 0;
		return false;
	}

	UChar fill = (inColor == kBlack) ? 0xFF : 0x00;
	if (fLineBits > inRun)
	{
		fLineBits -= inRun;
		if (inColor == kBlack)
			fLineByte |= kLowBits[inRun] << fLineBits;
		*outBytes = 0;
		return true;
	}

	UChar * start = fLine;
	if (fLineBits != 8)
	{
		if (inColor == kBlack)
			fLineByte |= kLowBits[fLineBits];
		inRun -= fLineBits;
		*fLine++ = fLineByte;
		fLineBits = 8;
		fLineByte = 0;
	}

	int bytes = inRun >> 3;
	int room = fLineEnd - fLine;
	if (bytes > room)
		bytes = room;
	inRun -= bytes << 3;
	while (bytes-- > 0)
		*fLine++ = fill;

	if (inRun < 8)
	{
		if (inColor == kBlack)
			fLineByte = kHighBits[inRun];
		fLineBits = 8 - inRun;
	}
	*outBytes = fLine - start;
	return inRun < 8;
}


/*------------------------------------------------------------------------------
	Read the next code of a color: a run, a make-up run (0x40..), an end of
	line (0x68) or not a code (0xFE).
------------------------------------------------------------------------------*/

int
TT4FaxLine::MHGetNextCode(RunColor inColor)
{
	const UChar * tree;
	if (inColor == kWhite)
		tree = kMajorIndexWhite[GetBits(4)];
	else if (GetNextBit() == 1)
		return (GetNextBit() == 1) ? 2 : 3;
	else if (GetNextBit() == 1)
		return (GetNextBit() == 1) ? 4 : 1;
	else if (GetNextBit() == 1)
		return (GetNextBit() == 1) ? 5 : 6;
	else
		tree = kMajorIndexBlack[GetBits(2)];

	int node = 1;
	while (tree[node] == 0xFF)
		node = node * 2 + GetNextBit();
	int code = tree[node];
	if (code == 0x68)
		while (GetNextBit() == 0)
			;
	return code;
}


