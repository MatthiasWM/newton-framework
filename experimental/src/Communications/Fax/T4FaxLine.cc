int
TT4FaxLine::GetBits(int inCount)
{
	int bits = 0;
	while (inCount-- > 0)
		bits = (bits << 1) | GetNextBit();
	return bits;
}


void
TT4FaxLine::Init(UChar * inRing, int inSize)
{
	fRing = inRing;
	fRingSize = inSize;
	fRingEnd = inRing + inSize;
	Reset();
}


void
TT4FaxLine::Reset(void)
{
	fPut = fRing;
	fGet = fRing;
	fBitsInByte = 0;
	fLapped = false;
}


