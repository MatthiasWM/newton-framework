/*------------------------------------------------------------------------------
	The end of a page: RTC, six ends of line.
------------------------------------------------------------------------------*/

int
T4AddRTC(UChar * outCode)
{
	*outCode++ = 0x00; *outCode++ = 0x08; *outCode++ = 0x80;
	*outCode++ = 0x00; *outCode++ = 0x08; *outCode++ = 0x80;
	*outCode++ = 0x00; *outCode++ = 0x08; *outCode++ = 0x80;
	*outCode = 0x00;
	return 10;
}


